# Сортировка пузырьком.
# Проходим по массиву и меняем местами соседей, если они стоят неправильно.
# После первого прохода самый большой элемент "всплывает" в конец,
# после второго второй по величине и т.д.
# Сложность O(n^2), для больших массивов медленно.


def bubble_sort(arr):
    n = len(arr)
    for i in range(n - 1):
        swapped = False
        # последние i элементов уже на своих местах, их не трогаем
        for j in range(n - 1 - i):
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swapped = True
        if not swapped:
            # за целый проход ни одного обмена, значит уже отсортировано
            break
    return arr
